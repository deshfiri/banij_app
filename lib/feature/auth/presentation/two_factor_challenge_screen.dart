import 'package:flutter/material.dart';
import 'package:flutter_screenutil/flutter_screenutil.dart';

import '../../../constants/color.dart';
import '../../../helpers/all_routes.dart';
import '../../../helpers/toast.dart';
import '../../../helpers/ui_helpers.dart';
import '../../../networks/api_access.dart';

class TwoFactorChallengeScreen extends StatefulWidget {
  final String challengeToken;

  const TwoFactorChallengeScreen({
    super.key,
    required this.challengeToken,
  });

  @override
  State<TwoFactorChallengeScreen> createState() => _TwoFactorChallengeScreenState();
}

class _TwoFactorChallengeScreenState extends State<TwoFactorChallengeScreen> {
  final TextEditingController _codeController = TextEditingController();
  final TextEditingController _recoveryCodeController = TextEditingController();
  final TextEditingController _deviceNameController = TextEditingController(text: 'Mobile Device');

  bool _isUsingRecoveryCode = false;
  bool _isLoading = false;

  @override
  void dispose() {
    _codeController.dispose();
    _recoveryCodeController.dispose();
    _deviceNameController.dispose();
    super.dispose();
  }

  Future<void> _verifyTwoFactor() async {
    final code = _codeController.text.trim();
    final recoveryCode = _recoveryCodeController.text.trim();
    final deviceName = _deviceNameController.text.trim();

    if (_isUsingRecoveryCode) {
      if (recoveryCode.isEmpty) {
        ToastUtil.showErrorMessage('Please enter your recovery code');
        return;
      }
    } else {
      if (code.isEmpty || code.length < 6) {
        ToastUtil.showErrorMessage('Please enter a valid 6-digit authenticator code');
        return;
      }
    }

    setState(() {
      _isLoading = true;
    });

    try {
      final body = {
        "challenge_token": widget.challengeToken,
        if (!_isUsingRecoveryCode) "code": code,
        if (_isUsingRecoveryCode) "recovery_code": recoveryCode,
        "device_name": deviceName.isNotEmpty ? deviceName : 'Mobile Device',
      };

      await twoFactorChallengeRxObj.verifyTwoFactor(body);
      if (!mounted) return;
      ToastUtil.showSuccessMessage('Two-factor authentication successful!');
      Navigator.pushNamedAndRemoveUntil(context, Routes.dashboardScreen, (route) => false);
    } catch (e) {
      String err = e.toString().replaceAll('Exception: ', '');
      ToastUtil.showErrorMessage(err.isNotEmpty ? err : 'Invalid 2FA verification code');
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColorsTheme.background(context),
      appBar: AppBar(
        backgroundColor: AppColorsTheme.cardBg(context),
        elevation: 1,
        leading: IconButton(
          icon: Icon(Icons.arrow_back_rounded, color: AppColorsTheme.textMainColor(context)),
          onPressed: () => Navigator.pop(context),
        ),
        title: Text(
          'Two-Factor Authentication',
          style: TextStyle(
            fontSize: 18.sp,
            fontWeight: FontWeight.bold,
            color: AppColorsTheme.textMainColor(context),
          ),
        ),
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: EdgeInsets.symmetric(horizontal: 24.w, vertical: 24.h),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Container(
                padding: EdgeInsets.all(16.w),
                decoration: BoxDecoration(
                  color: primaryOrange.withValues(alpha: 0.1),
                  shape: BoxShape.circle,
                ),
                child: Icon(Icons.security_rounded, color: primaryOrange, size: 36.sp),
              ),
              UIHelper.verticalSpace(20.h),
              Text(
                'Security Verification',
                style: TextStyle(
                  fontSize: 22.sp,
                  fontWeight: FontWeight.w900,
                  color: AppColorsTheme.textMainColor(context),
                ),
              ),
              UIHelper.verticalSpace(8.h),
              Text(
                _isUsingRecoveryCode
                    ? 'Please enter one of your emergency recovery codes to complete sign-in.'
                    : 'Please enter the 6-digit authentication code generated by your authenticator app.',
                style: TextStyle(
                  fontSize: 13.5.sp,
                  color: AppColorsTheme.textMutedColor(context),
                  height: 1.4,
                ),
              ),
              UIHelper.verticalSpace(30.h),

              if (!_isUsingRecoveryCode) ...[
                Text(
                  'Authenticator Code',
                  style: TextStyle(fontSize: 13.sp, fontWeight: FontWeight.bold, color: AppColorsTheme.textMainColor(context)),
                ),
                UIHelper.verticalSpace(8.h),
                TextField(
                  controller: _codeController,
                  keyboardType: TextInputType.number,
                  maxLength: 6,
                  style: TextStyle(fontSize: 18.sp, fontWeight: FontWeight.bold, letterSpacing: 4, color: AppColorsTheme.textMainColor(context)),
                  decoration: InputDecoration(
                    hintText: '123456',
                    counterText: '',
                    hintStyle: TextStyle(fontSize: 16.sp, color: AppColorsTheme.textMutedColor(context), letterSpacing: 4),
                    contentPadding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
                    filled: true,
                    fillColor: AppColorsTheme.cardBg(context),
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(14.r),
                      borderSide: BorderSide(color: AppColorsTheme.borderColor(context)),
                    ),
                    focusedBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(14.r),
                      borderSide: BorderSide(color: primaryOrange, width: 1.5.w),
                    ),
                  ),
                ),
              ] else ...[
                Text(
                  'Recovery Code',
                  style: TextStyle(fontSize: 13.sp, fontWeight: FontWeight.bold, color: AppColorsTheme.textMainColor(context)),
                ),
                UIHelper.verticalSpace(8.h),
                TextField(
                  controller: _recoveryCodeController,
                  style: TextStyle(fontSize: 14.sp, color: AppColorsTheme.textMainColor(context)),
                  decoration: InputDecoration(
                    hintText: 'Enter recovery code',
                    hintStyle: TextStyle(fontSize: 13.sp, color: AppColorsTheme.textMutedColor(context)),
                    contentPadding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
                    filled: true,
                    fillColor: AppColorsTheme.cardBg(context),
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(14.r),
                      borderSide: BorderSide(color: AppColorsTheme.borderColor(context)),
                    ),
                    focusedBorder: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(14.r),
                      borderSide: BorderSide(color: primaryOrange, width: 1.5.w),
                    ),
                  ),
                ),
              ],

              UIHelper.verticalSpace(20.h),
              Text(
                'Device Name',
                style: TextStyle(fontSize: 13.sp, fontWeight: FontWeight.bold, color: AppColorsTheme.textMainColor(context)),
              ),
              UIHelper.verticalSpace(8.h),
              TextField(
                controller: _deviceNameController,
                style: TextStyle(fontSize: 13.5.sp, color: AppColorsTheme.textMainColor(context)),
                decoration: InputDecoration(
                  hintText: 'Mobile Device',
                  hintStyle: TextStyle(fontSize: 13.sp, color: AppColorsTheme.textMutedColor(context)),
                  contentPadding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
                  filled: true,
                  fillColor: AppColorsTheme.cardBg(context),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(14.r),
                    borderSide: BorderSide(color: AppColorsTheme.borderColor(context)),
                  ),
                ),
              ),
              UIHelper.verticalSpace(24.h),

              // Toggle between code & recovery code
              Center(
                child: TextButton(
                  onPressed: () {
                    setState(() {
                      _isUsingRecoveryCode = !_isUsingRecoveryCode;
                    });
                  },
                  child: Text(
                    _isUsingRecoveryCode ? 'Use authenticator code instead' : 'Use a recovery code instead',
                    style: TextStyle(
                      fontSize: 13.sp,
                      fontWeight: FontWeight.bold,
                      color: primaryOrange,
                    ),
                  ),
                ),
              ),
              UIHelper.verticalSpace(20.h),

              // Verify Button
              SizedBox(
                width: double.infinity,
                child: ElevatedButton(
                  onPressed: _isLoading ? null : _verifyTwoFactor,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: primaryOrange,
                    foregroundColor: Colors.white,
                    padding: EdgeInsets.symmetric(vertical: 16.h),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14.r)),
                    elevation: 0,
                  ),
                  child: _isLoading
                      ? SizedBox(
                          width: 20.w,
                          height: 20.h,
                          child: const CircularProgressIndicator(color: Colors.white, strokeWidth: 2),
                        )
                      : Text(
                          'Verify & Sign In',
                          style: TextStyle(fontSize: 15.sp, fontWeight: FontWeight.bold),
                        ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
