/// Second sign-in step: authenticator code (or recovery code) + device name.
class TwoFactorChallengeScreen extends StatefulWidget {
  final String challengeToken;

  const TwoFactorChallengeScreen({
    super.key,
    required this.challengeToken,
  });

  @override
  State<TwoFactorChallengeScreen> createState() => _TwoFactorChallengeScreenState();
}

class _TwoFactorChallengeScreenState extends State<TwoFactorChallengeScreen> {
  final TextEditingController _codeController = TextEditingController();
  final TextEditingController _recoveryCodeController = TextEditingController();
  final TextEditingController _deviceNameController = TextEditingController(text: 'Mobile Device');

  @override
  void initState() {
    super.initState();
    // Prefill with this phone's name (shown in the signed-in devices list).
    deviceLabel().then((label) {
      if (mounted && _deviceNameController.text == 'Mobile Device') _deviceNameController.text = label;
    });
  }

  bool _isUsingRecoveryCode = false;
  bool _isLoading = false;

  @override
  void dispose() {
    _codeController.dispose();
    _recoveryCodeController.dispose();
    _deviceNameController.dispose();
    super.dispose();
  }

  Future<void> _verifyTwoFactor() async {
    final code = _codeController.text.trim();
    final recoveryCode = _recoveryCodeController.text.trim();
    final deviceName = _deviceNameController.text.trim();

    if (_isUsingRecoveryCode) {
      if (recoveryCode.isEmpty) {
        ToastUtil.showErrorMessage('Please enter your recovery code'.tr);
        return;
      }
    } else {
      if (code.isEmpty || code.length < 6) {
        ToastUtil.showErrorMessage('Please enter a valid 6-digit authenticator code'.tr);
        return;
      }
    }

    setState(() {
      _isLoading = true;
    });

    try {
      final body = {
        "challenge_token": widget.challengeToken,
        if (!_isUsingRecoveryCode) "code": code,
        if (_isUsingRecoveryCode) "recovery_code": recoveryCode,
        "device_name": deviceName.isNotEmpty ? deviceName : 'Mobile Device',
      };

      final res = await twoFactorChallengeRxObj.verifyTwoFactor(body);
      if (!mounted) return;
      final token = res.accessToken;
      if (token == null || token.isEmpty) {
        ToastUtil.showErrorMessage(res.message ?? 'Verification did not return a session. Please sign in again.'.tr);
        return;
      }
      // `user` arrives as JSON: parse it (reading fields off the raw map would crash).
      final rawUser = res.user;
      final user = rawUser is Map ? UserModel.fromJson(Map<String, dynamic>.from(rawUser)) : null;
      // Same checks as the password step (account present, active).
      final problem = loginResponseProblem(LoginResponse(token: token, user: user));
      if (problem != null) {
        ToastUtil.showErrorMessage(problem);
        return;
      }
      final authProvider = context.read<AuthProvider>();
      ToastUtil.showSuccessMessage('Two-factor authentication successful!'.tr);
      await authProvider.completeSignIn(
        token: token,
        user: user,
        isSupplier: authProvider.isSupplierLogin || (user?.isSupplier ?? false),
      );
    } catch (e) {
      String err = e.toString().replaceAll('Exception: ', '');
      ToastUtil.showErrorMessage(err.isNotEmpty ? err : 'Invalid 2FA verification code'.tr);
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return AuthScaffold(
      heroHeight: 300,
      showToggles: false,
      onBack: () => Navigator.pop(context),
      body: AuthScrollBody(
        children: [
          const AuthHeroIcon(icon: Icons.security_rounded),
          UIHelper.verticalSpace(12.h),
          AuthHeroTitle(
            title: 'Security Verification'.tr,
            subtitle: (_isUsingRecoveryCode
                    ? 'Please enter one of your emergency recovery codes to complete sign-in.'
                    : 'Please enter the 6-digit authentication code generated by your authenticator app.')
                .tr,
          ),
          UIHelper.verticalSpace(22.h),
          AuthFormCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                if (!_isUsingRecoveryCode) ...[
                  _FieldLabel('Authenticator Code'.tr),
                  _AuthTextField(
                    controller: _codeController,
                    hintText: '123456',
                    keyboardType: TextInputType.number,
                    maxLength: 6,
                    isCode: true,
                  ),
                ] else ...[
                  _FieldLabel('Recovery Code'.tr),
                  _AuthTextField(controller: _recoveryCodeController, hintText: 'Enter recovery code'.tr),
                ],
                UIHelper.verticalSpace(16.h),
                _FieldLabel('Device Name'.tr),
                _AuthTextField(controller: _deviceNameController, hintText: 'Mobile Device'),
                UIHelper.verticalSpace(10.h),
                AuthTextLink(
                  label: (_isUsingRecoveryCode ? 'Use authenticator code instead' : 'Use a recovery code instead').tr,
                  icon: _isUsingRecoveryCode ? Icons.pin_outlined : Icons.key_rounded,
                  onTap: () {
                    setState(() {
                      _isUsingRecoveryCode = !_isUsingRecoveryCode;
                    });
                  },
                ),
                UIHelper.verticalSpace(10.h),
                GradientButton(
                  label: 'Verify & Sign In'.tr,
                  trailingIcon: Icons.verified_user_rounded,
                  isLoading: _isLoading,
                  onPressed: _verifyTwoFactor,
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}

class _FieldLabel extends StatelessWidget {
  final String text;

  const _FieldLabel(this.text);

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: EdgeInsets.only(bottom: 8.h),
      child: Text(
        text,
        style: TextStyle(fontSize: 13.sp, fontWeight: FontWeight.w700, color: AppColorsTheme.textMainColor(context)),
      ),
    );
  }
}

/// Filled, rounded text field with the orange focus border used on this screen.
/// [isCode] gives the large spaced-out digits style for the 6-digit code.
class _AuthTextField extends StatelessWidget {
  final TextEditingController controller;
  final String hintText;
  final TextInputType? keyboardType;
  final int? maxLength;
  final bool isCode;

  const _AuthTextField({
    required this.controller,
    required this.hintText,
    this.keyboardType,
    this.maxLength,
    this.isCode = false,
  });

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    OutlineInputBorder border(Color color, [double width = 1]) => OutlineInputBorder(
          borderRadius: BorderRadius.circular(14.r),
          borderSide: BorderSide(color: color, width: width),
        );

    return TextField(
      controller: controller,
      keyboardType: keyboardType,
      maxLength: maxLength,
      textAlign: isCode ? TextAlign.center : TextAlign.start,
      style: TextStyle(
        fontSize: isCode ? 20.sp : 13.5.sp,
        fontWeight: isCode ? FontWeight.w900 : FontWeight.w500,
        letterSpacing: isCode ? 8 : 0,
        color: AppColorsTheme.textMainColor(context),
      ),
      decoration: InputDecoration(
        hintText: hintText,
        counterText: '',
        hintStyle: TextStyle(
          fontSize: isCode ? 18.sp : 13.sp,
          letterSpacing: isCode ? 8 : 0,
          color: AppColorsTheme.textMutedColor(context),
        ),
        contentPadding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
        filled: true,
        fillColor: isDark ? AppColorsTheme.innerCardBg(context) : lightBackground,
        border: border(AppColorsTheme.borderColor(context)),
        enabledBorder: border(isDark ? darkCardBorderColor : primaryOrange.withValues(alpha: 0.2)),
        focusedBorder: border(primaryOrange, 1.5.w),
      ),
    );
  }
}
